// E2: cadastro pelo app. Ana cria a conta e a casa (de 1 pessoa: sem rodízio, uma coluna, sem
// Equilíbrio/Juntas), faz a configuração só com o nome dela, gera o convite; Bia abre o link, vê
// de quem é, cria a conta e entra na casa; a casa passa a ser de 2 pessoas. Convite usado não vale.
const { chromium } = require(require('child_process').execSync('npm root -g').toString().trim() + '/playwright')
const { execSync } = require('child_process')
const fs = require('fs')
const S = (process.env.E2E_SHOTS || '/tmp/ninho-e2e/shots') + '/r59'; fs.rmSync(S, { recursive: true, force: true }); fs.mkdirSync(S, { recursive: true })
const AXE = fs.readFileSync(require.resolve('axe-core/axe.min.js', { paths: [__dirname + '/..'] }), 'utf8')
const APP = 'http://localhost:3124'
const PSQL = 'runuser -u postgres -- /usr/lib/postgresql/16/bin/psql -X -h localhost -p 54330 -U postgres -d ninho'
const sql = q => execSync(`${PSQL} -At -c "${q.replace(/"/g, '\\"')}"`).toString().trim()
let fails = 0
const check = (c, m) => { console.log((c ? '  ok - ' : '  FALHOU - ') + m); if (!c) fails++ }
const errs = [], wait = ms => new Promise(r => setTimeout(r, ms))
const axe = async (p, sel) => { await p.addScriptTag({ content: AXE }); return p.evaluate(async s => (await window.axe.run(document.querySelector(s), { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'] } })).violations.map(v => `${v.id}(${v.nodes.length})`), sel) }
const phone = { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, timezoneId: 'America/Sao_Paulo', locale: 'pt-BR' }
;(async () => {
  const b = require('../lib/mute-agua.js')(await chromium.launch())

  console.log('1. Ana cria a conta')
  const c1 = await b.newContext(phone), p = await c1.newPage(); p.on('pageerror', e => errs.push(e.message))
  await p.goto(APP); await p.waitForSelector('#lg-email')
  await p.locator('.lg-lnk', { hasText: 'Criar conta' }).click(); await wait(300)
  await p.fill('#lg-email', 'ana@cadastro-e2e.test'); await p.fill('#lg-pw', 'senha-ana-1234'); await p.fill('#lg-pw2', 'senha-ana-9999')
  await p.locator('.lg-b').click(); await wait(500)
  check(/não são iguais/.test(await p.locator('.lg-err').innerText().catch(() => '')), 'senhas diferentes: avisa')
  await p.fill('#lg-pw2', 'senha-ana-1234')
  const v0 = await axe(p, '.lg'); check(v0.length === 0, 'axe sem problemas no cadastro' + (v0.length ? ': ' + v0.join(', ') : ''))
  await p.screenshot({ path: S + '/01-criar-conta.png' })
  await p.locator('.lg-b').click()

  console.log('2. Ana cria a casa')
  await p.waitForSelector('#hs-name', { timeout: 15000 })
  check(await p.locator('[role=tab][aria-selected=true]', { hasText: 'Criar minha casa' }).count() === 1, 'sem convite: começa em "Criar minha casa"')
  await p.fill('#hs-name', 'Ana'); await p.fill('#hs-house', 'Casa da Ana')
  await p.screenshot({ path: S + '/02-criar-casa.png' })
  await p.locator('.lg-b', { hasText: 'Criar minha casa' }).click()
  await p.waitForSelector('.onb', { timeout: 20000 })
  const H = sql(`select household_id from household_members m join auth.users u on u.id=m.user_id where u.email='ana@cadastro-e2e.test'`)
  check(/^[0-9a-f-]{36}$/.test(H), 'casa criada, com a Ana dentro')
  check(sql(`select features::text from households where id='${H}'`) === '{"solo": true}', 'casa de 1 pessoa, sem IA e sem Sobrou')

  console.log('3. Configuração só com o nome dela')
  await p.locator('.onb .btn-p', { hasText: 'Começar' }).click(); await wait(400)
  check(await p.locator('input[aria-label="Nome da segunda pessoa"]').count() === 0, 'sem o campo da segunda pessoa')
  await p.locator('.onb [role=radio]', { hasText: 'Não' }).click(); await wait(200)
  for (let i = 0; i < 8; i++) { const c = p.locator('.onb .btn-p', { hasText: 'Continuar' }); if (!await c.count()) break; await c.click(); await wait(300) }
  await p.locator('.onb .btn-p', { hasText: 'Confirmar e criar' }).click(); await wait(2500)
  await p.locator('.onb .btn', { hasText: 'Ir para o Início' }).click(); await wait(1500)

  console.log('4. Início de 1 pessoa')
  check(await p.locator('.seg').count() === 0, 'sem a troca entre as duas pessoas')
  check(await p.locator('.pcard').count() === 1, 'uma coluna só')
  await p.screenshot({ path: S + '/03-inicio-solo.png' })
  await p.locator('.bnb', { hasText: 'Nós' }).click(); await wait(700)
  const nos = await p.locator('main').innerText()
  check(!/Juntas/.test(nos) && !/Equilíbrio/.test(nos), 'Nós sem Juntas e sem Equilíbrio')

  console.log('5. Convite')
  await p.locator('.top-prof').click(); await wait(800)
  const integ = p.locator('.card', { hasText: 'Integrantes' })
  check(await integ.locator('.field-row').count() === 1, 'Integrantes: só a Ana')
  await integ.locator('.btn', { hasText: 'Gerar link de convite' }).click(); await wait(1200)
  const link = await integ.locator('.conv-l').inputValue()
  check(/\/\?convite=[0-9a-f]{32}$/.test(link), 'link do convite: ' + link.replace(/[0-9a-f]{28}$/, '…'))
  const v1 = await axe(p, '.conv'); check(v1.length === 0, 'axe sem problemas no convite' + (v1.length ? ': ' + v1.join(', ') : ''))
  await integ.screenshot({ path: S + '/04-convite.png' })
  await c1.close()

  console.log('6. Bia abre o link')
  const c2 = await b.newContext(phone), q = await c2.newPage(); q.on('pageerror', e => errs.push(e.message))
  await q.goto(link.replace(/^https?:\/\/[^/]+/, APP)); await q.waitForSelector('#lg-email')
  await wait(800)
  check(/Ana[\s\S]*Casa da Ana/.test(await q.locator('.lg-inv').innerText().catch(() => '')), 'o login mostra de quem é o convite')
  check(await q.locator('#lg-pw2').count() === 1, 'e já começa em "Criar conta"')
  check(!/convite=/.test(q.url()), 'o código sai da barra de endereço')
  await q.screenshot({ path: S + '/05-convite-login.png' })
  await q.fill('#lg-email', 'bia@cadastro-e2e.test'); await q.fill('#lg-pw', 'senha-bia-1234'); await q.fill('#lg-pw2', 'senha-bia-1234')
  await q.locator('.lg-b').click()
  await q.waitForSelector('#hs-name', { timeout: 15000 })
  check(await q.locator('[role=tab][aria-selected=true]', { hasText: 'Tenho um convite' }).count() === 1, 'depois de criar a conta: "Tenho um convite" já preenchido')
  await q.fill('#hs-name', 'Bia')
  await q.locator('.lg-b', { hasText: 'Entrar na casa' }).click()
  await q.waitForSelector('.pcard:not([data-hide="1"])', { timeout: 20000 }); await wait(1500)
  check(sql(`select who from household_members m join auth.users u on u.id=m.user_id where u.email='bia@cadastro-e2e.test'`) === 's', 'Bia entrou na casa da Ana, como a segunda pessoa')
  check(sql(`select features->>'solo' from households where id='${H}'`) === 'false', 'a casa passou a ser de 2 pessoas')
  check(await q.locator('.seg').count() === 1, 'Início com as duas pessoas')
  await q.screenshot({ path: S + '/06-bia-inicio.png' })
  await c2.close()

  console.log('7. Convite usado não vale')
  const c3 = await b.newContext(phone), r = await c3.newPage(); r.on('pageerror', e => errs.push(e.message))
  await r.goto(link.replace(/^https?:\/\/[^/]+/, APP)); await r.waitForSelector('#lg-email'); await wait(800)
  check(await r.locator('.lg-inv').count() === 0, 'convite usado: o login não mostra convite')
  await r.locator('.lg-lnk', { hasText: 'Criar conta' }).click().catch(() => {})
  await r.fill('#lg-email', 'caio@cadastro-e2e.test'); await r.fill('#lg-pw', 'senha-caio-1234'); await r.fill('#lg-pw2', 'senha-caio-1234')
  await r.locator('.lg-b').click(); await r.waitForSelector('#hs-name', { timeout: 15000 })
  await r.locator('[role=tab]', { hasText: 'Tenho um convite' }).click(); await r.fill('#hs-name', 'Caio')
  await r.fill('#hs-code', link); await wait(800)
  check(/vencido|usado/.test(await r.locator('.lg-box').innerText()), 'explica que o convite venceu ou já foi usado')
  await r.locator('.lg-b', { hasText: 'Entrar na casa' }).click(); await wait(1200)
  check(/Convite inválido, usado ou vencido/.test(await r.locator('.lg-err').innerText().catch(() => '')), 'e não entra')
  check(sql(`select count(*) from household_members where household_id='${H}'`) === '2', 'a casa continua com 2 pessoas')
  await c3.close()

  check(errs.length === 0, 'sem erros de JavaScript' + (errs.length ? ': ' + errs.slice(0, 3).join(' | ') : ''))
  await b.close()
  console.log(fails ? `== r59: ${fails} FALHA(S)` : '== r59: TUDO OK'); process.exit(fails ? 1 : 0)
})().catch(e => { console.error(e); console.log('== r59: ERRO'); process.exit(1) })
