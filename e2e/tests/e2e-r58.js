// E1: módulos por casa. Uma casa nova (sem IA, sem Sobrou) responde "têm pet?" na configuração,
// não vê Cães, Sobrou nem os atalhos de IA; o servidor recusa IA e Sobrou para ela; o banco não
// deixa ela ligar a IA; ela liga os pets em Ajustes. No Telegram, sem IA ela usa os comandos, e
// os avisos do Sobrou do bom dia só vão para a casa que tem o Sobrou. A casa de teste segue igual.
const { chromium } = require(require('child_process').execSync('npm root -g').toString().trim() + '/playwright')
const { execSync } = require('child_process')
const fs = require('fs')
const S = (process.env.E2E_SHOTS || '/tmp/ninho-e2e/shots') + '/r58'; fs.rmSync(S, { recursive: true, force: true }); fs.mkdirSync(S, { recursive: true })
const AXE = fs.readFileSync(require.resolve('axe-core/axe.min.js', { paths: [__dirname + '/..'] }), 'utf8')
const APP = 'http://localhost:3124', GW = 'http://localhost:54321', TG = 'http://localhost:9555', AI = 'http://localhost:9556'
const H = '11111111-1111-1111-1111-111111111111', H2 = '58585858-0000-0000-0000-000000000001'
const PSQL = 'runuser -u postgres -- /usr/lib/postgresql/16/bin/psql -X -h localhost -p 54330 -U postgres -d ninho'
const sql = q => execSync(`${PSQL} -At -c "${q.replace(/"/g, '\\"')}"`).toString().trim()
let fails = 0
const check = (c, m) => { console.log((c ? '  ok - ' : '  FALHOU - ') + m); if (!c) fails++ }
const errs = [], wait = ms => new Promise(r => setTimeout(r, ms))
const tgCalls = async () => (await fetch(TG + '/__calls')).json()
const aiCalls = async () => (await fetch(AI + '/__calls')).json()
const hook = update => fetch(APP + '/api/telegram/webhook', { method: 'POST', headers: { 'content-type': 'application/json', 'x-telegram-bot-api-secret-token': 'segredo-webhook-local' }, body: JSON.stringify(update) })
const cron = path => fetch(APP + path, { headers: { authorization: 'Bearer segredo-do-cron-local' } })
const anon = require('../stack/token.js')('anon')
const login = async (email, password) => (await (await fetch(`${GW}/auth/v1/token?grant_type=password`, { method: 'POST', headers: { 'content-type': 'application/json', apikey: anon }, body: JSON.stringify({ email, password }) })).json()).access_token
const axe = async (p, sel) => { await p.addScriptTag({ content: AXE }); return p.evaluate(async s => (await window.axe.run(document.querySelector(s), { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'] } })).violations.map(v => `${v.id}(${v.nodes.length})`), sel) }
;(async () => {
  // casa nova, criada como o administrador criaria hoje (a E2 traz o cadastro pelo app)
  sql(`insert into households (id, name) values ('${H2}', 'Casa nova teste')`)
  sql(`insert into auth.users (id, email, encrypted_password) values ('00000000-0000-0000-0000-0000000058a1','ana@casanova.test','senha-ana-123'),('00000000-0000-0000-0000-0000000058a2','bia@casanova.test','senha-bia-123')`)
  sql(`select public.ninho_link_member('ana@casanova.test','g','${H2}')`); sql(`select public.ninho_link_member('bia@casanova.test','s','${H2}')`)
  check(sql(`select coalesce(features->>'ia','x') || '/' || coalesce(features->>'sobrou','x') from households where id='${H2}'`) === 'x/x', 'casa nova começa sem IA e sem Sobrou')

  const b = require('../lib/mute-agua.js')(await chromium.launch())
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, timezoneId: 'America/Sao_Paulo', locale: 'pt-BR' })
  const p = await ctx.newPage(); p.on('pageerror', e => errs.push(e.message)); p.on('dialog', d => d.accept())
  await p.goto(APP); await p.waitForSelector('#lg-email')
  await p.fill('#lg-email', 'ana@casanova.test'); await p.fill('#lg-pw', 'senha-ana-123'); await p.locator('.lg-b').click()

  console.log('1. Configuração inicial: têm pet?')
  await p.waitForSelector('.onb', { timeout: 20000 })
  await p.locator('.onb .btn-p', { hasText: 'Começar' }).click(); await wait(400)
  await p.fill('input[aria-label="Nome da primeira pessoa"]', 'Ana'); await p.fill('input[aria-label="Nome da segunda pessoa"]', 'Bia')
  await p.locator('.onb .btn-p', { hasText: 'Continuar' }).click(); await wait(300)
  check(/pet/.test(await p.locator('.onb').innerText()) && await p.locator('.onb [role=alert], .onb .inline-err, .onb .err').count() >= 0, 'precisa responder se tem pet')
  check(await p.locator('h1#onb-h', { hasText: 'Quem faz parte' }).count() === 1, 'não avança sem responder')
  await p.locator('.onb [role=radio]', { hasText: 'Não' }).click(); await wait(200)
  check(await p.locator('.onb input[placeholder="Nome do cão"]').count() === 0, 'sem pet: sem os campos de cão')
  await p.screenshot({ path: S + '/01-pet.png' })
  const v0 = await axe(p, '.onb'); check(v0.length === 0, 'axe sem problemas na pergunta' + (v0.length ? ': ' + v0.join(', ') : ''))
  for (let i = 0; i < 8; i++) { const c = p.locator('.onb .btn-p', { hasText: 'Continuar' }); if (!await c.count()) break; await c.click(); await wait(300) }
  await p.locator('.onb .btn-p', { hasText: 'Confirmar e criar' }).click(); await wait(2500)
  check(sql(`select features->>'pets' from households where id='${H2}'`) === 'false', 'a resposta vai para os módulos da casa (sem pets)')
  check(sql(`select count(*) from dogs where household_id='${H2}'`) === '0', 'nenhum cão criado')
  await p.locator('.onb .btn', { hasText: 'Ir para o Início' }).click(); await wait(1500)

  console.log('2. A casa nova não vê o que não tem')
  const tabs = await p.locator('.bnb').allInnerTexts()
  check(!tabs.some(t => /Cães/.test(t)) && tabs.length === 4, 'sem a aba Cães: ' + tabs.map(t => t.trim()).join(' · '))
  const gap = await p.evaluate(() => { const n = document.querySelector('.bnav'); const bs = [...n.querySelectorAll('.bnb')]; return Math.round(n.getBoundingClientRect().right - bs[bs.length - 1].getBoundingClientRect().right) })
  check(gap <= 12, `a barra de baixo ocupa a largura toda com 4 abas (sobra ${gap}px)`)
  check(await p.locator('.chip', { hasText: 'Planejar o dia' }).count() === 0 && await p.locator('.chip', { hasText: 'Faxinão' }).count() === 0, 'sem os atalhos de IA no topo do Início')
  await p.evaluate(() => window.scrollTo(0, document.body.scrollHeight)); await wait(1200)
  check(await p.locator('.sob, .sob-slim').count() === 0, 'sem o cartão do Sobrou')
  await p.screenshot({ path: S + '/02-inicio.png', fullPage: true })
  await p.evaluate(() => window.scrollTo(0, 0))
  await p.locator('.mob-fab, .fab').first().click(); await wait(600)
  const qa = await p.locator('.modal').innerText()
  check(!/com IA|Perguntar ao Ninho|Faxinão/.test(qa) && !/Cuidado dos cães/.test(qa), 'o + sem IA e sem cães')
  await p.keyboard.press('Escape'); await wait(400)
  await p.locator('.bnb', { hasText: 'Casa' }).click(); await wait(700)
  await p.locator('.subtab', { hasText: 'Mais' }).first().click(); await wait(500)
  check(!/Faxinão/.test(await p.locator('main').innerText()), 'Casa › Mais sem o Faxinão')

  console.log('3. O servidor recusa IA e Sobrou para ela')
  const tok = await login('ana@casanova.test', 'senha-ana-123')
  const post = (path, body) => fetch(APP + path, { method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${tok}` }, body: JSON.stringify(body) })
  const r1 = await post('/api/ai/pergunta', { householdId: H2, question: 'Como tiro mancha de café?' })
  check(r1.status === 403 && /IA não está ligada/.test((await r1.json()).error), 'Perguntar: 403 "A IA não está ligada para esta casa"')
  const r2 = await post('/api/ai/faxinao', { householdId: H2, text: 'banheiro e cozinha' })
  check(r2.status === 403, 'Faxinão: 403')
  const r3 = await post('/api/sobrou', { householdId: H2 })
  check(r3.status === 403 && /Sobrou não está ligado/.test((await r3.json()).error), 'Sobrou: 403 (as finanças da outra casa não vazam)')
  check((await aiCalls()).length === 0, 'nenhuma chamada à IA saiu')

  console.log('4. O banco não deixa ela ligar a IA')
  const rest = (method, path, body) => fetch(`${GW}/rest/v1/${path}`, { method, headers: { 'content-type': 'application/json', apikey: anon, authorization: `Bearer ${tok}`, prefer: 'return=representation' }, body: JSON.stringify(body) })
  const u1 = await rest('PATCH', `households?id=eq.${H2}`, { features: { ia: true, sobrou: true, pets: false } })
  check(u1.status >= 400 && sql(`select coalesce(features->>'ia','x') from households where id='${H2}'`) === 'x', `mudar a linha da casa: recusado (${u1.status})`)
  const u2 = await rest('POST', 'rpc/ninho_set_feature', { p_household_id: H2, p_key: 'ia', p_on: true })
  check(u2.status >= 400, `ligar a IA pela função: recusado (${u2.status})`)
  const u3 = await rest('POST', 'rpc/ninho_set_feature', { p_household_id: H, p_key: 'pets', p_on: false })
  check(u3.status === 403 && sql(`select features->>'pets' from households where id='${H}'`) === 'true', `mexer na outra casa: recusado (${u3.status})`)

  console.log('5. Ela liga os pets em Ajustes')
  await p.locator('.top-prof').click(); await wait(800)
  const card = p.locator('#aj-modulos')
  check(/IA[\s\S]*desligada/i.test(await card.innerText()), 'Módulos da casa: IA desligada (só informação)')
  const v1 = await axe(p, '#aj-modulos'); check(v1.length === 0, 'axe sem problemas no cartão' + (v1.length ? ': ' + v1.join(', ') : ''))
  await card.screenshot({ path: S + '/03-modulos.png' })
  check(!/Sobrou/.test(await p.locator('main').innerText()), 'Ajustes sem nada do Sobrou')
  await card.locator('input[aria-label^="Pets"]').check(); await wait(1500)
  check(sql(`select features->>'pets' from households where id='${H2}'`) === 'true', 'pets ligados no banco')
  check((await p.locator('.bnb').allInnerTexts()).some(t => /Cães/.test(t)), 'a aba Cães aparece')
  await ctx.close()

  console.log('6. A casa de teste segue com tudo')
  const c2 = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, timezoneId: 'America/Sao_Paulo', locale: 'pt-BR' })
  const q = await c2.newPage(); q.on('pageerror', e => errs.push(e.message))
  await q.goto(APP); await q.waitForSelector('#lg-email')
  await q.fill('#lg-email', 'giovanna@ninho.test'); await q.fill('#lg-pw', 'senha-gio-123'); await q.locator('.lg-b').click()
  await q.waitForSelector('.pcard', { timeout: 20000 }); await wait(1500)
  check((await q.locator('.bnb').allInnerTexts()).length === 5, 'as 5 abas, com Cães')
  check(await q.locator('.chip', { hasText: 'Planejar o dia' }).count() === 1, 'com o atalho de IA')
  const tg = await login('giovanna@ninho.test', 'senha-gio-123')
  const r4 = await fetch(APP + '/api/sobrou', { method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${tg}` }, body: JSON.stringify({ householdId: H }) })
  check(r4.status === 200 && (await r4.json()).configured === true, 'o Sobrou continua funcionando para ela')
  await b.close()

  console.log('7. Telegram')
  sql(`insert into telegram_links (household_id, who, chat_id, linked_at, active, morning, weekly, tasks, evening) values ('${H2}','g',5801,now(),true,true,true,true,true),('${H}','g',5802,now(),true,true,true,true,true)`)
  await fetch(TG + '/__reset'); await fetch(AI + '/__reset')
  await hook({ update_id: 58001, message: { message_id: 1, chat: { id: 5801 }, from: { id: 5801 }, date: Math.floor(Date.now() / 1000), text: 'comprei pão e preciso lavar o carro amanhã' } }); await wait(800)
  const m1 = (await tgCalls()).filter(c => c.method === 'sendMessage' && c.body.chat_id === 5801).pop()
  check(m1 && /Não entendi/.test(m1.body.text) && (await aiCalls()).length === 0, 'casa sem IA: texto livre não vai para a IA')
  await hook({ update_id: 58002, message: { message_id: 2, chat: { id: 5801 }, from: { id: 5801 }, date: Math.floor(Date.now() / 1000), voice: { file_id: 'x', duration: 3 } } }); await wait(800)
  const m2 = (await tgCalls()).filter(c => c.method === 'sendMessage' && c.body.chat_id === 5801).pop()
  check(m2 && /áudio usa a IA/.test(m2.body.text), 'áudio: avisa que usa a IA')
  await hook({ update_id: 58003, message: { message_id: 3, chat: { id: 5801 }, from: { id: 5801 }, date: Math.floor(Date.now() / 1000), text: '+ leite' } }); await wait(800)
  check(sql(`select count(*) from shopping_items where household_id='${H2}' and lower(title)='leite'`) === '1', 'os comandos continuam: "+ leite" vai para a lista')
  await fetch(TG + '/__reset')
  await cron('/api/cron/morning'); await wait(500)
  const morning = (await tgCalls()).filter(c => c.method === 'sendMessage')
  const mNova = morning.find(c => c.body.chat_id === 5801), mTeste = morning.find(c => c.body.chat_id === 5802)
  check(!!mNova && !/Conta de luz teste|vermelho/.test(mNova.body.text), 'bom dia da casa nova: sem os avisos do Sobrou')
  check(!!mTeste && /Conta de luz teste/.test(mTeste.body.text), 'bom dia da casa de teste: com o aviso do Sobrou')

  check(errs.length === 0, 'sem erros de JavaScript' + (errs.length ? ': ' + errs.slice(0, 3).join(' | ') : ''))
  console.log(fails ? `== r58: ${fails} FALHA(S)` : '== r58: TUDO OK'); process.exit(fails ? 1 : 0)
})().catch(e => { console.error(e); console.log('== r58: ERRO'); process.exit(1) })
